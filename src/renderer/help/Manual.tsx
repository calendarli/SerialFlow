          <article id="modbus" data-title="Modbus RTU 主站 从站 功能码 寄存器 CRC">
            <h2>Modbus RTU</h2>
            <p>
              拖动快捷指令栏右侧分隔条可调整宽度，自动记住设置；最小宽度与其他 TAB 内容区一致，为
              330px。双击分隔条恢复默认宽度。
            </p>
            <p>
              选择已打开串口后，读取或轮询保持寄存器，使用 H06 / H10 写入寄存器。软件负责 RTU 报文和
              CRC，并校验设备响应。
            </p>
            <p>
              左侧“快捷指令”用于状态切换、启停和运动控制，与自动回复规则页一样使用右键菜单管理：
              空白处右键可直接添加指令或分组；新指令可选择已有分组，默认保存到“未分组”。
              分组上右键添加指令、重命名或删除分组；指令上右键编辑或删除。 无需先创建设备配置。
              点击指令名称立即写入，使用“通信设置”中的串口、从站地址和字序。
              指令包含名称、寄存器地址、数据和数据类型，支持 HEX16、UINT16、INT32、UINT32、FLOAT32。
              拖动 ⋮⋮ 调整分组或指令顺序，指令可拖入其他分组。地址和整数数据支持十进制或 0x
              前缀十六进制。
            </p>
            <p>
              工具栏的“配置管理器”显示配置列表。右键“保存配置”直接保存主页当前已读取或已确认写入的寄存器地址、数据类型、数值、从站地址和字序，不弹出编辑窗口。
              名称自动使用当前映射名称和从站地址，重名时追加序号。未读取的数据不会补零；暂无数据、32
              位数据不完整或非有限数值时会提示先读取有效数据。
              配置行右键可删除；点击配置整行任意位置选择配置，再应用并写入。
              快捷指令和设备配置独立保存在本机，切换或删除设备配置不会修改快捷指令。
              连接串口后选择配置，点击“应用并写入配置”按列表顺序执行，
              或点击单条指令的“写入”。写入采用所选配置的从站地址和字序，串口参数仍由串口配置页管理。
              批量写入会停止轮询，逐条等待确认；失败、断线或点击停止后不再发送后续指令。
              已写入数据不会回滚，超时或断线时应读回核对。停止按钮会等待当前指令响应。
              设备配置与原有寄存器映射 JSON 独立保存，不包含在工程或映射导出中。
            </p>
            <div className="tip">
              Modbus 地址通常同时存在十进制、十六进制和 4xxxx
              文档表示法。遇到偏移一位时，请确认设备文档使用的是协议地址还是寄存器编号。
            </div>
          </article>

